import { createFileRoute } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";
import {
  Activity,
  AlertTriangle,
  Battery,
  Clock3,
  Pause,
  Play,
  RotateCcw,
  Thermometer,
  Zap,
} from "lucide-react";
import {
  CartesianGrid,
  Line,
  LineChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { Button } from "@/components/ui/button";
import { Panel, StatusChip } from "@/components/battery/ui";
import {
  analyzeReadings,
  createReading,
  PROTOTYPE_THRESHOLDS,
  SCENARIOS,
  type HealthStatus,
  type ScenarioId,
  type SimulatedReading,
} from "@/lib/battery/simulator";

export const Route = createFileRoute("/_shell/battery-simulator")({
  component: BatterySimulatorPage,
});

const HEALTH_STATUS_MAP = {
  HEALTHY: "normal",
  WATCH: "monitor",
  DEGRADED: "warning",
  CRITICAL: "critical",
} as const;

function BatterySimulatorPage() {
  const [scenario, setScenario] = useState<ScenarioId>("healthy");
  const [running, setRunning] = useState(false);
  const [readings, setReadings] = useState<SimulatedReading[]>(() => [createReading("healthy", 0)]);
  const nextStep = useRef(1);
  const latest = readings.at(-1)!;
  const analysis = analyzeReadings(readings);
  const scenarioName = SCENARIOS.find((item) => item.id === scenario)?.label ?? "Healthy Operation";

  useEffect(() => {
    if (!running) return;

    const timer = window.setInterval(() => {
      const reading = createReading(scenario, nextStep.current);
      nextStep.current += 1;
      setReadings((current) => [...current, reading].slice(-60));
    }, 1000);

    return () => window.clearInterval(timer);
  }, [running, scenario]);

  const chooseScenario = (nextScenario: ScenarioId) => {
    setRunning(false);
    setScenario(nextScenario);
    nextStep.current = 1;
    setReadings([createReading(nextScenario, 0)]);
  };

  const reset = () => {
    setRunning(false);
    setScenario("healthy");
    nextStep.current = 1;
    setReadings([createReading("healthy", 0)]);
  };

  const chartData = readings.map((reading) => ({
    ...reading,
    elapsed: `T+${reading.step}s`,
  }));
  const power = latest.voltage * latest.current;
  const cells = latest.cells;

  return (
    <div className="space-y-5 pb-4">
      <header className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h1 className="text-xl font-bold text-foreground">Battery Health Simulator</h1>
            <span className="inline-flex items-center gap-1.5 rounded-sm border border-primary/30 bg-primary/5 px-2 py-1 text-[10px] font-bold tracking-wide text-primary">
              <span className="size-1.5 rounded-full bg-primary" /> SIMULATION MODE
            </span>
          </div>
          <p className="mt-1 max-w-2xl text-xs text-muted-foreground">
            Explore repeatable battery operating patterns. Every measurement on this page is
            generated by the simulator.
          </p>
        </div>
        <div className="flex items-center gap-2 text-xs text-muted-foreground">
          <span
            className={`size-2 rounded-full ${running ? "animate-pulse bg-success" : "bg-muted-foreground/50"}`}
          />
          {running ? "Running · 1 reading/sec" : "Paused"}
        </div>
      </header>

      <Panel
        title="Scenario controls"
        description="Selecting a scenario starts it from its first reproducible reading"
      >
        <div className="flex flex-col gap-4 xl:flex-row xl:items-end xl:justify-between">
          <label className="block min-w-0 flex-1 text-xs font-medium text-muted-foreground">
            Scenario
            <select
              value={scenario}
              onChange={(event) => chooseScenario(event.target.value as ScenarioId)}
              className="mt-1.5 h-10 w-full rounded-md border border-input bg-background px-3 text-sm font-medium text-foreground outline-none focus-visible:ring-2 focus-visible:ring-ring sm:max-w-md"
            >
              {SCENARIOS.map((item) => (
                <option key={item.id} value={item.id}>
                  {item.label}
                </option>
              ))}
            </select>
          </label>
          <div className="flex flex-wrap items-center gap-2">
            <Button type="button" size="sm" onClick={() => setRunning(true)} disabled={running}>
              <Play /> Start
            </Button>
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={() => setRunning(false)}
              disabled={!running}
            >
              <Pause /> Pause
            </Button>
            <Button type="button" size="sm" variant="outline" onClick={reset}>
              <RotateCcw /> Reset
            </Button>
            <span className="ml-1 text-xs text-muted-foreground">
              {scenarioName} · {readings.length} readings
            </span>
          </div>
        </div>
      </Panel>

      <section
        aria-label="Latest simulated measurements"
        className="grid grid-cols-2 gap-3 lg:grid-cols-3 2xl:grid-cols-6"
      >
        <Measurement
          label="Pack voltage"
          value={`${latest.voltage.toFixed(2)} V`}
          detail={`Recent ${analysis.voltageMinimum.toFixed(2)}–${analysis.voltageMaximum.toFixed(2)} V`}
          icon={Battery}
        />
        <Measurement
          label="Current"
          value={`${latest.current.toFixed(1)} A`}
          detail="Positive means discharging"
          icon={Zap}
        />
        <Measurement
          label="Temperature"
          value={`${latest.temperature.toFixed(1)} °C`}
          detail={`Recent max ${analysis.maximumTemperature.toFixed(1)} °C`}
          icon={Thermometer}
        />
        <Measurement
          label="Power"
          value={`${power.toFixed(0)} W`}
          detail="Voltage × current; positive discharge"
          icon={Activity}
        />
        <Measurement
          label="Cell imbalance"
          value={`${(analysis.cellImbalance * 1000).toFixed(0)} mV`}
          detail="Maximum cell − minimum cell"
          icon={Battery}
        />
        <Measurement
          label="Operating state"
          value={analysis.operatingState}
          detail="Based on simulator current convention"
          icon={Clock3}
        />
      </section>

      <section aria-label="Generated measurements over time" className="grid gap-4 xl:grid-cols-3">
        <TrendChart
          title="Pack voltage"
          unit="V"
          data={chartData}
          dataKey="voltage"
          color="#1687a7"
        />
        <TrendChart
          title="Battery current"
          unit="A"
          data={chartData}
          dataKey="current"
          color="#c77b19"
        />
        <TrendChart
          title="Battery temperature"
          unit="°C"
          data={chartData}
          dataKey="temperature"
          color="#d04b3e"
        />
      </section>

      <section className="grid gap-4 xl:grid-cols-[minmax(0,1fr)_minmax(0,1.4fr)]">
        <Panel
          title="Cell voltages"
          description="Four generated cell readings; no individual cell health grades"
        >
          <div className="grid grid-cols-2 gap-x-5 gap-y-4 sm:grid-cols-4 xl:grid-cols-2 2xl:grid-cols-4">
            {cells.map((voltage, index) => (
              <div key={index} className="border-l-2 border-primary/40 pl-3">
                <p className="text-[11px] text-muted-foreground">Cell {index + 1}</p>
                <p className="mt-1 text-lg font-semibold tabular-nums text-foreground">
                  {voltage.toFixed(3)}{" "}
                  <span className="text-xs font-normal text-muted-foreground">V</span>
                </p>
              </div>
            ))}
          </div>
          <div className="mt-4 flex items-center justify-between border-t border-border pt-3 text-xs">
            <span className="text-muted-foreground">Maximum − minimum</span>
            <strong className="tabular-nums text-foreground">
              {analysis.cellImbalance.toFixed(3)} V ({(analysis.cellImbalance * 1000).toFixed(0)}{" "}
              mV)
            </strong>
          </div>
        </Panel>

        <Panel
          title="Battery health assessment"
          description="Recent trend assessment and immediate threshold checks are evaluated separately"
          action={
            <StatusChip status={HEALTH_STATUS_MAP[analysis.health]} label={analysis.health} />
          }
        >
          <div className="grid gap-5 md:grid-cols-2">
            <div>
              <h3 className="mb-2 text-xs font-semibold text-foreground">Detected patterns</h3>
              {analysis.patterns.length ? (
                <ul className="space-y-2">
                  {analysis.patterns.map((pattern) => (
                    <li key={pattern} className="flex gap-2 text-xs text-foreground">
                      <Activity className="size-3.5 shrink-0 text-primary" />
                      {pattern}
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="text-xs text-muted-foreground">
                  No configured trend pattern detected.
                </p>
              )}
              <h3 className="mb-2 mt-4 text-xs font-semibold text-foreground">
                Assessment reasons
              </h3>
              <ul className="space-y-2">
                {analysis.reasons.map((reason) => (
                  <li
                    key={reason}
                    className="flex gap-2 text-xs leading-relaxed text-muted-foreground"
                  >
                    <span className="mt-1.5 size-1 shrink-0 rounded-full bg-muted-foreground/60" />
                    {reason}
                  </li>
                ))}
              </ul>
              <p className="mt-3 text-[11px] text-muted-foreground">
                {analysis.historyReady
                  ? `Trend window: ${readings.slice(-PROTOTYPE_THRESHOLDS.trendWindowReadings).length} readings · ΔV ${analysis.voltageChange?.toFixed(2)} V · ΔI ${analysis.currentChange?.toFixed(1)} A · ΔT ${analysis.temperatureChange?.toFixed(1)} °C`
                  : `Trend evaluation requires ${PROTOTYPE_THRESHOLDS.minimumTrendReadings} readings. Immediate faults are still checked.`}
              </p>
            </div>
            <div className="border-t border-border pt-4 md:border-l md:border-t-0 md:pl-5 md:pt-0">
              <h3 className="mb-2 text-xs font-semibold text-foreground">Active fault alerts</h3>
              {analysis.alerts.length ? (
                <ul className="space-y-2">
                  {analysis.alerts.map((alert) => (
                    <li
                      key={alert.id}
                      className={`flex gap-2 rounded-sm border px-3 py-2.5 text-xs leading-relaxed ${alert.severity === "CRITICAL" ? "border-destructive/25 bg-critical-soft text-destructive" : "border-warning/40 bg-warning-soft text-warning-foreground"}`}
                    >
                      <AlertTriangle className="mt-0.5 size-3.5 shrink-0" />
                      <span>
                        <strong>{alert.severity}:</strong> {alert.message}
                      </span>
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="text-xs text-muted-foreground">No active threshold alerts.</p>
              )}
            </div>
          </div>
        </Panel>
      </section>

      <p className="border-l-2 border-warning/70 bg-warning-soft/50 px-3 py-2.5 text-[11px] leading-relaxed text-muted-foreground">
        Prototype simulation only. It does not measure a physical scooter battery or send readings
        to telemetry services. Thresholds are configurable demonstration values, not universal EV
        safety limits. Simulated degradation is not proof of electrochemical degradation; this
        classification is not a validated State of Health estimate and does not demonstrate
        real-world prediction accuracy. Positive current denotes discharge, negative current
        charging, and near-zero current idle; power is voltage × current under that convention.
      </p>
    </div>
  );
}

function Measurement({
  label,
  value,
  detail,
  icon: Icon,
}: {
  label: string;
  value: string;
  detail: string;
  icon: typeof Battery;
}) {
  return (
    <div className="card-surface min-w-0 p-3.5">
      <div className="flex items-center justify-between gap-2">
        <p className="truncate text-[11px] font-medium text-muted-foreground">{label}</p>
        <Icon className="size-4 shrink-0 text-primary" />
      </div>
      <p className="mt-2 truncate text-lg font-semibold tabular-nums text-foreground">{value}</p>
      <p className="mt-1 min-h-8 text-[10px] leading-relaxed text-muted-foreground">{detail}</p>
    </div>
  );
}

function TrendChart({
  title,
  unit,
  data,
  dataKey,
  color,
}: {
  title: string;
  unit: string;
  data: (SimulatedReading & { elapsed: string })[];
  dataKey: "voltage" | "current" | "temperature";
  color: string;
}) {
  return (
    <Panel title={title} description={`Generated history · ${unit}`}>
      <div className="h-48 w-full">
        <ResponsiveContainer width="100%" height="100%">
          <LineChart data={data} margin={{ top: 6, right: 8, bottom: 0, left: -18 }}>
            <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="var(--border)" />
            <XAxis
              dataKey="elapsed"
              tickLine={false}
              axisLine={false}
              tick={{ fontSize: 10, fill: "var(--muted-foreground)" }}
              minTickGap={24}
            />
            <YAxis
              tickLine={false}
              axisLine={false}
              tick={{ fontSize: 10, fill: "var(--muted-foreground)" }}
              width={42}
            />
            <Tooltip
              contentStyle={{
                borderRadius: 4,
                borderColor: "var(--border)",
                background: "var(--card)",
                fontSize: 11,
              }}
              formatter={(value) => [`${Number(value).toFixed(2)} ${unit}`, title]}
              labelStyle={{ color: "var(--muted-foreground)" }}
            />
            <Line
              type="monotone"
              dataKey={dataKey}
              stroke={color}
              strokeWidth={2}
              dot={false}
              activeDot={{ r: 3 }}
              isAnimationActive={false}
            />
          </LineChart>
        </ResponsiveContainer>
      </div>
    </Panel>
  );
}
